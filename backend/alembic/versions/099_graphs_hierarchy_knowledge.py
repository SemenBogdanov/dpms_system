def _article_table() -> sa.TableClause:
    return sa.table(
        "knowledge_articles",
        sa.column("id", sa.Uuid()),
        sa.column("slug", sa.String(160)),
        sa.column("title", sa.String(255)),
        sa.column("summary", sa.String(500)),
        sa.column("section", sa.String(80)),
        sa.column("body", sa.Text()),
        sa.column(
            "status",
            postgresql.ENUM("draft", "published", name="knowledgestatus", create_type=False),
        ),
        sa.column("sort_order", sa.Integer()),
        sa.column("created_by_id", sa.Uuid()),
        sa.column("updated_by_id", sa.Uuid()),
        sa.column("created_at", sa.DateTime(timezone=True)),
        sa.column("updated_at", sa.DateTime(timezone=True)),
        sa.column("published_at", sa.DateTime(timezone=True)),
    )


def upgrade() -> None:
    bind = op.get_bind()
    table = _article_table()
    insert = sqlite.insert if bind.dialect.name == "sqlite" else postgresql.insert
    # An occupied slug or ID belongs to its existing owner, even if it is a draft.
    statement = insert(table).values(
        **ARTICLE,
        created_by_id=None,
        updated_by_id=None,
        created_at=sa.func.current_timestamp(),
        updated_at=sa.func.current_timestamp(),
        published_at=sa.func.current_timestamp(),
    ).on_conflict_do_nothing()
    bind.execute(statement)


def downgrade() -> None:
    table = _article_table()
    # Exact snapshot plus edit markers protects API edits, including reverted text.
    unchanged = [table.c[name] == value for name, value in ARTICLE.items()]
    op.get_bind().execute(
        table.delete().where(
            *unchanged,
            table.c.created_by_id.is_(None),
            table.c.updated_by_id.is_(None),
            table.c.created_at.is_not(None),
            table.c.updated_at == table.c.created_at,
            table.c.published_at == table.c.created_at,
        )
    )
